"""
PDB (Protein Data Bank) file format I/O.

Used for molecular visualization and compatibility with bioinformatics tools.
"""

import numpy as np
from fibernet.core.network import FiberNetwork
from fibernet.core.fiber import Fiber


def to_pdb(
    network: FiberNetwork,
    filename: str,
    bead_spacing: float = None,
    atom_name: str = "CA",
    residue_name: str = "FBR",
) -> str:
    """Export fiber network to PDB format.
    
    Parameters
    ----------
    network : FiberNetwork
        Fiber network.
    filename : str
        Output file path.
    bead_spacing : float
        Spacing between beads.
    atom_name : str
        PDB atom name.
    residue_name : str
        PDB residue name.

    Exports above 9,999 beads number residues separately for each chain
    label. Exports that exceed fixed-width atom serial or residue sequence
    capacity raise ValueError before opening the destination. Connectivity
    records follow all coordinate records.
    """
    if bead_spacing is None:
        bead_spacing = network.mean_radius * 3

    bead_counts = [max(2, int(fiber.length / bead_spacing) + 1)
                   for fiber in network.fibers]
    atom_count = sum(bead_counts)
    if atom_count > 99999:
        raise ValueError("PDB atom serial field supports at most 99999 beads")

    chain_local_numbering = atom_count > 9999
    if chain_local_numbering:
        for index in range(26):
            if sum(bead_counts[index::26]) > 9999:
                chain = chr(65 + index)
                raise ValueError(f"PDB residue sequence field supports at most 9999 beads in chain {chain}")
    
    with open(filename, 'w') as f:
        f.write(f"HEADER    FIBER NETWORK\n")
        f.write(f"REMARK    Generated by FiberNet\n")
        f.write(f"REMARK    {network.num_fibers} fibers\n")
        
        atom_id = 1
        residue_id = 1
        next_residue_by_chain = [1] * 26
        
        for f_idx, (fiber, num_pts) in enumerate(zip(network.fibers, bead_counts)):
            
            if num_pts == 2:
                pts = np.array([fiber.start_point, fiber.end_point])
            else:
                pts = fiber.resample(num_pts).centerline
            
            chain_index = f_idx % 26
            chain_id = chr(65 + chain_index)  # A-Z
            if chain_local_numbering:
                residue_id = next_residue_by_chain[chain_index]
            
            for pt in pts:
                # PDB coordinate convention (Å)
                x, y, z = pt * 10.0  # Convert to Å if in nm
                
                line = (
                    f"ATOM  {atom_id:5d} {atom_name:4s} {residue_name:3s} {chain_id:1s}"
                    f"{residue_id:4d}    "
                    f"{x:8.3f}{y:8.3f}{z:8.3f}"
                    f"  1.00  0.00\n"
                )
                f.write(line)
                atom_id += 1
                residue_id += 1
            if chain_local_numbering:
                next_residue_by_chain[chain_index] = residue_id
            
            f.write("TER\n")

        first_atom_id = 1
        for num_pts in bead_counts:
            for atom in range(first_atom_id, first_atom_id + num_pts - 1):
                f.write(f"CONECT{atom:5d}{atom + 1:5d}\n")
            first_atom_id += num_pts
        
        f.write("END\n")
    
    return filename


def from_pdb(filename: str, bead_radius: float = 0.1) -> FiberNetwork:
    """Import fiber network from PDB file.
    
    Reads the first pair from each CONECT record to reconstruct fiber chains.
    Fixed-width five-column serials and legacy whitespace-separated pairs are
    accepted. This is not a general branched PDB topology importer; coordinates
    are interpreted as angstroms and returned in nanometers, and proximity
    crosslinks are inferred after chain reconstruction.
    """
    atoms = {}
    conect = []
    
    with open(filename, 'r') as f:
        for line in f:
            if line.startswith("ATOM") or line.startswith("HETATM"):
                aid = int(line[6:11])
                x = float(line[30:38]) / 10.0  # Å to nm
                y = float(line[38:46]) / 10.0
                z = float(line[46:54]) / 10.0
                atoms[aid] = np.array([x, y, z])
            
            elif line.startswith("CONECT"):
                # Standard PDB serials occupy adjacent five-column fields;
                # five-digit values need not have whitespace between them.
                # Preserve the legacy whitespace parser for nonstandard input.
                body = line[6:].rstrip()
                fields = [body[k:k + 5] for k in range(0, len(body), 5)]
                canonical = (len(body) >= 10 and len(body) % 5 == 0 and
                             all(field.lstrip(' ').isascii() and field.lstrip(' ').isdigit()
                                 for field in fields))
                if canonical:
                    i, j = int(fields[0]), int(fields[1])
                else:
                    parts = body.split()
                    if len(parts) < 2:
                        continue
                    try:
                        i, j = int(parts[0]), int(parts[1])
                    except ValueError:
                        continue
                conect.append((i, j))
    
    if not atoms:
        return FiberNetwork()
    
    adj = {}
    for i, j in conect:
        adj.setdefault(i, []).append(j)
        adj.setdefault(j, []).append(i)
    
    visited = set()
    chains = []
    
    for start in atoms:
        if start in visited:
            continue
        chain = [start]
        visited.add(start)
        current = start
        while True:
            neighbors = [n for n in adj.get(current, []) if n not in visited]
            if not neighbors:
                break
            nxt = neighbors[0]
            chain.append(nxt)
            visited.add(nxt)
            current = nxt
        if len(chain) >= 2:
            chains.append(chain)
    
    net = FiberNetwork(dimension=3)
    for c_idx, chain in enumerate(chains):
        positions = np.array([atoms[aid] for aid in chain])
        fiber = Fiber(centerline=positions, radius=bead_radius, fiber_id=c_idx)
        net.add_fiber(fiber)
    
    net.auto_crosslink(threshold=3.0 * bead_radius)
    return net
