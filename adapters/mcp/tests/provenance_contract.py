def public(value):
    if isinstance(value,Model): return {k:public(v) for k,v in vars(value).items()}
    if isinstance(value,dict): return {k:public(v) for k,v in value.items()}
    if isinstance(value,(list,tuple)): return [public(v) for v in value]
    return value

