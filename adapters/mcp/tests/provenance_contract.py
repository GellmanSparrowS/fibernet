    def test_15_same_parsed_object_one_manifest_read(self):
        t, core, mp, m = self.make()
        with t:
            reads = []
            parsed = []
            digested = []
            original_read = NEW.read_file
            original_parse = NEW.strict_json
            original_canonical = NEW.canonical

            def read(path, *a, **kw):
                reads.append(str(path))
                return original_read(path, *a, **kw)

            def parse(raw):
                obj = original_parse(raw)
                parsed.append(obj)
                return obj

            def canonical(obj):
                digested.append(obj)
                return original_canonical(obj)
            with patch.object(NEW, 'read_file', read), patch.object(NEW, 'strict_json', parse), patch.object(NEW, 'canonical', canonical):
                result = self.verification(core, mp)
