"""PDB identifiers stay in their fields across export and re-import."""

import os

import numpy as np
import pytest

from fibernet import Fiber, FiberNetwork
from fibernet.api import export, load
from fibernet.gen import ZigZagGenerator


def make_fiber(start, end):
    return Fiber.straight(start, end, radius=.1, segments=1)


def test_pdb_small_multifiber_export_preserves_atom_records_and_defers_connectivity(tmp_path):
    network = FiberNetwork([
        make_fiber([0, 0, 0], [1, 0, 0]),
        make_fiber([0, 1, 0], [1, 1, 0]),
    ])
    path = tmp_path / 'small.pdb'
    export(network, path, bead_spacing=2.)
    lines = [
        'HEADER    FIBER NETWORK',
        'REMARK    Generated by FiberNet',
        'REMARK    2 fibers',
        'ATOM      1 CA   FBR A   1       0.000   0.000   0.000  1.00  0.00',
        'ATOM      2 CA   FBR A   2      10.000   0.000   0.000  1.00  0.00',
        'TER',
        'ATOM      3 CA   FBR B   3       0.000  10.000   0.000  1.00  0.00',
        'ATOM      4 CA   FBR B   4      10.000  10.000   0.000  1.00  0.00',
        'TER',
        'CONECT    1    2',
        'CONECT    3    4',
        'END',
    ]
    assert path.read_bytes() == (os.linesep.join(lines) + os.linesep).encode('ascii')


def test_pdb_default_zigzag_roundtrip_keeps_fixed_width_and_chain_residue_ids(tmp_path):
    network = ZigZagGenerator(n_cols=3, n_rows=3).to_fiber_network()
    path = tmp_path / 'zigzag.pdb'
    export(network, path)
    lines = path.read_text().splitlines()
    atoms = [line for line in lines if line.startswith('ATOM')]
    assert network.num_fibers == 45
    assert len(atoms) == 14895
    assert all(len(line) == 66 for line in atoms)
    assert [int(line[6:11]) for line in atoms] == list(range(1, len(atoms) + 1))
    first_connection = next(index for index, line in enumerate(lines) if line.startswith('CONECT'))
    assert lines[first_connection - 1] == 'TER'
    assert lines[-1] == 'END'
    connections = lines[first_connection:-1]
    assert len(connections) == len(atoms) - network.num_fibers
    assert all(line.startswith('CONECT') for line in connections)

    by_chain = {}
    for line in atoms:
        by_chain.setdefault(line[21], []).append(int(line[22:26]))
    assert list(by_chain) == [chr(65 + index) for index in range(26)]
    assert all(indices == list(range(1, len(indices) + 1))
               for indices in by_chain.values())

    restored = load(path)
    assert restored.num_fibers == network.num_fibers
    bead_spacing = network.mean_radius * 3
    offset = 0
    for index, (fiber, output) in enumerate(zip(network.fibers, restored.fibers)):
        count = max(2, int(fiber.length / bead_spacing) + 1)
        assert all(line[21] == chr(65 + index % 26)
                   for line in atoms[offset:offset + count])
        offset += count
        assert output.num_points == count
        expected = np.linspace(fiber.start_point, fiber.end_point, count)
        np.testing.assert_allclose(output.centerline, expected, rtol=0., atol=5.000001e-5)
    assert offset == len(atoms)


def test_pdb_atom_serial_overflow_does_not_overwrite_existing_file(tmp_path):
    network = FiberNetwork([make_fiber([0, 0, 0], [1, 0, 0])])
    path = tmp_path / 'existing.pdb'
    original = b'existing output'
    path.write_bytes(original)
    with pytest.raises(ValueError, match='atom serial'):
        export(network, path, bead_spacing=1e-6)
    assert path.read_bytes() == original


def test_pdb_reused_chain_residue_overflow_does_not_overwrite_existing_file(tmp_path):
    network = FiberNetwork([
        make_fiber([0, i, 0], [5. if i in (0, 26) else .0001, i, 0])
        for i in range(27)
    ])
    path = tmp_path / 'existing.pdb'
    original = b'existing output'
    path.write_bytes(original)
    with pytest.raises(ValueError, match='residue sequence.*chain A'):
        export(network, path, bead_spacing=.001)
    assert path.read_bytes() == original
